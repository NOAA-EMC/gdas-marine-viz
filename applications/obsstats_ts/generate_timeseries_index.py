def parse_timeseries_filename(filename):
    """
    Parse a timeseries PNG filename to extract platform, variable, basin, and plot type.

    Expected formats:
    - Platform_Name_-_Basin_Name_timeseries.png (individual experiment)
    - Platform_Name_-_Basin_Name_comparison.png (multi-experiment comparison)
    - Experiment_Name_-_Platform_Name_-_Basin_Name_timeseries.png (individual experiment with experiment prefix)

    Examples:
    - Surface_Drifters_Temp_-_Global_comparison.png
    - Argo_Profiles_Salt_0-10m_-_Atlantic_comparison.png
    - SST_VIIRS_N20_-_Pacific_comparison.png
    - cp402d_-_AMSR2_Ice_Concentration_North_-_Global_timeseries.png

    Returns:
        tuple: (platform, variable, basin, plot_type, depth_info)
    """
    # Remove .png extension
    basename = filename.replace('.png', '')

    # Determine plot type
    if basename.endswith('_timeseries'):
        plot_type = 'timeseries'
        basename = basename.replace('_timeseries', '')
    elif basename.endswith('_comparison'):
        plot_type = 'comparison'
        basename = basename.replace('_comparison', '')
    else:
        return None, None, None, None, None

    # Find the separator "_-_" to split parts
    separator = '_-_'
    if separator not in basename:
        return None, None, None, None, None

    parts = basename.split(separator)

    # Handle different formats:
    # Format 1: Platform_-_Basin (2 parts)
    # Format 2: Experiment_-_Platform_-_Basin (3 parts)
    if len(parts) == 2:
        platform_part = parts[0]
        basin_part = parts[1]
    elif len(parts) == 3:
        # Skip the experiment name (first part) and use platform and basin
        platform_part = parts[1]
        basin_part = parts[2]
    else:
        return None, None, None, None, None

    # Extract variable and depth information from platform name
    variable = None
    depth_info = None

    # Check for depth information in platform name (e.g., "0-10m", "300-2000m")
    depth_pattern = r'_(\d+[-‐]\d+m)$'  # Match depth at end like "_0-10m"
    depth_match = re.search(depth_pattern, platform_part)
    if depth_match:
        depth_info = depth_match.group(1)
        platform_part = platform_part.replace('_' + depth_info, '')

    # Check for variable type indicators
    if platform_part.endswith('_Temp'):
        variable = 'Temperature'
        platform_part = platform_part.replace('_Temp', '')
    elif platform_part.endswith('_Salt'):
        variable = 'Salinity'
        platform_part = platform_part.replace('_Salt', '')
    elif platform_part.startswith('SST_'):
        variable = 'SST'
    elif platform_part.startswith('ADT_'):
        variable = 'ADT'
    elif (platform_part.startswith('AMSR2_') or
          'ICEC' in platform_part.upper() or
          'Ice_Concentration' in platform_part or
          platform_part.lower().startswith('amsr2')):
        variable = 'ICEC'
    else:
        variable = 'Temperature'  # Default assumption

    # Convert underscores to spaces for display
    platform_display = platform_part.replace('_', ' ')
    basin_display = basin_part.replace('_', ' ')

    return platform_display.strip(), variable, basin_display.strip(), plot_type, depth_info


def organize_timeseries_files(directory):
    """
    Organize PNG files by platform type, variable, and basin.

    Returns:
        dict: Organized structure with platforms, variables, basins, and plot types
    """
    files_data = defaultdict(lambda: defaultdict(lambda: defaultdict(lambda: defaultdict(str))))

    # Get all PNG files in directory
    png_files = [f for f in os.listdir(directory) if f.endswith('.png')]

    for filename in png_files:
        platform, variable, basin, plot_type, depth_info = parse_timeseries_filename(filename)

        if platform and variable and basin and plot_type:
            # Create a platform key that includes depth info if present
            platform_key = platform
            if depth_info:
                platform_key = f"{platform} ({depth_info})"

            files_data[platform_key][variable][basin][plot_type] = filename

    return files_data


def load_config_experiments(config_file):
    """Load experiment names from configuration file."""
    if not config_file or not os.path.exists(config_file):
        return []

    try:
        with open(config_file, 'r') as f:
            config = yaml.safe_load(f)

        if 'experiments' in config and isinstance(config['experiments'], dict):
            return list(config['experiments'].keys())
        else:
            return []
    except Exception as e:
        print(f"Warning: Failed to load config file {config_file}: {e}")
        return []


def get_unique_platforms(files_data):
    """Get sorted list of unique platform types."""
    platforms = list(files_data.keys())

    # Custom sorting to group related platforms together
    def sort_key(platform):
        # Put surface drifters first
        if 'Drifter' in platform:
            return (0, platform)
        # Group Argo by variable and depth
        elif 'Argo' in platform:
            if 'Temp' in platform or 'Temperature' in platform:
                return (1, platform)
            elif 'Salt' in platform or 'Salinity' in platform:
                return (2, platform)
            else:
                return (1, platform)
        # Put SST platforms next
        elif 'SST' in platform:
            return (3, platform)
        # Put ICEC/AMSR2 platforms after SST
        elif ('AMSR2' in platform or 'ICEC' in platform.upper() or
              'Ice Concentration' in platform or 'amsr2' in platform.lower()):
            return (4, platform)
        else:
            return (5, platform)

    return sorted(platforms, key=sort_key)


def get_unique_variables(files_data):
    """Get sorted list of unique variables."""
    variables = set()
    for platform_data in files_data.values():
        variables.update(platform_data.keys())

    # Preferred order for variables
    variable_order = ['Temperature', 'Salinity', 'ADT', 'SST', 'ICEC']
    return [var for var in variable_order if var in variables]


def get_unique_basins(files_data):
    """Get sorted list of unique ocean basins."""
    basins = set()
    for platform_data in files_data.values():
        for variable_data in platform_data.values():
            basins.update(variable_data.keys())

    # Preferred order for ocean basins
    basin_order = ['Global', 'Arctic', 'Atlantic', 'Indian', 'Pacific', 'Southern']
    return [basin for basin in basin_order if basin in basins]


