def main():
    parser = argparse.ArgumentParser(
        description='Generate HTML index for marine observation timeseries figures',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python generate_timeseries_index.py /path/to/figures
  python generate_timeseries_index.py /path/to/figures --config config.yaml
  python generate_timeseries_index.py /path/to/figures --title "My Custom Analysis"
  python generate_timeseries_index.py ./real-time --experiments "CP4.02d,CP4.03"
        """
    )

    parser.add_argument('directory', help='Directory containing timeseries PNG files')
    parser.add_argument('--config', default=None,
                        help='Configuration YAML file to extract experiment names')
    parser.add_argument('--title', default=None,
                        help='Title for the HTML page (default: auto-generated)')
    parser.add_argument('--experiments', default=None,
                        help='Comma-separated list of experiment names')
    parser.add_argument('--output', default='timeseries_index.html',
                        help='Output HTML filename (default: timeseries_index.html)')

    args = parser.parse_args()

    # Validate directory
    if not os.path.isdir(args.directory):
        print(f"Error: Directory '{args.directory}' does not exist.")
        sys.exit(1)

    # Count PNG files
    png_files = [f for f in os.listdir(args.directory) if f.endswith('.png')]
    if not png_files:
        print(f"Error: No PNG files found in '{args.directory}'.")
        sys.exit(1)

    print(f"Found {len(png_files)} PNG files in '{args.directory}'")

    # Organize files
    print("Analyzing timeseries file structure...")
    files_data = organize_timeseries_files(args.directory)

    if not files_data:
        print("Error: No valid timeseries files found.")
        print("Expected filename formats:")
        print("  - Platform_Name_-_Basin_Name_timeseries.png")
        print("  - Platform_Name_-_Basin_Name_comparison.png")
        sys.exit(1)

    # Get experiment names
    experiments = []
    if args.experiments:
        experiments = [exp.strip() for exp in args.experiments.split(',')]
    elif args.config:
        experiments = load_config_experiments(args.config)

    # Print summary
    platforms = get_unique_platforms(files_data)
    variables = get_unique_variables(files_data)
    basins = get_unique_basins(files_data)

    print(f"Found {len(platforms)} platform types: {', '.join(platforms[:3])}{'...' if len(platforms) > 3 else ''}")
    print(f"Found {len(variables)} variables: {', '.join(variables)}")
    print(f"Found {len(basins)} ocean basins: {', '.join(basins)}")

    if experiments:
        print(f"Experiments: {', '.join(experiments)}")

    # Generate HTML
    print("Generating HTML index...")
    html_content = generate_timeseries_html(files_data, args.title, experiments, args.output)

    # Write output file
    output_path = os.path.join(args.directory, args.output)
    with open(output_path, 'w', encoding='utf-8') as f:
        f.write(html_content)

    print(f"HTML index generated: {output_path}")
    print(f"Open in browser: file://{os.path.abspath(output_path)}")


if __name__ == '__main__':
    main()
